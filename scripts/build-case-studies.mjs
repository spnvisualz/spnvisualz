// Writes /work/<slug>/index.html for every Selected Work project that does
// not have a hand-written page, from src/work/projects.js (title, tag,
// one-line description, media), src/work/caseStudies.js (on-screen copy,
// optional story and Visual Lab link) and the server price catalogue (the
// "from" price of the matching service, so it can never drift from what
// Stripe charges).
//
// Only files carrying GENERATED_MARK are ever overwritten; work/icekiid/ is
// hand-written and left alone. Run with `npm run case-studies`, then
// `npm run work` and `npm run sitemap` so the homepage ItemList and the
// sitemap pick the pages up.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { PROJECTS } from "../src/work/projects.js";
import { CASE_STUDIES } from "../src/work/caseStudies.js";
import { STORE_CATALOG } from "../server/store.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://spnvisualz.com";
export const GENERATED_MARK = "<!-- generated by scripts/build-case-studies.mjs; edit src/work/caseStudies.js instead -->";
export const PROJECT_CSS = "/work/project.css?v=20261102.1";

// Which service each project tag belongs to, and the catalogue SKUs whose
// cheapest price is the honest "from" figure for it.
export const SERVICE_FOR_TAG = {
  "ARTIST MOTION LOOP": { name: "Motion loop", skus: ["loop-basic", "loop-premium"] },
  "ARTIST INTRO": { name: "Intro visual", skus: ["intro-standard", "intro-premium"] },
  "ARTIST TITLE": { name: "Animated logo", skus: ["animated-logo"] },
  "LOGO MOTION": { name: "Animated logo", skus: ["animated-logo"] },
  "BRAND VISUAL": { name: "Visuals", skus: ["visuals-social", "visuals-brand"] },
  "ARTIST VISUALS": { name: "Visuals", skus: ["visuals-social", "visuals-brand"] }
};

// When the reel was first published on the site, from git history, so
// VideoObject.uploadDate is a real moment rather than a guess. Google wants
// a full ISO 8601 date-time with a timezone (a bare date is flagged as
// invalid / missing timezone), so this uses the commit's strict ISO time,
// e.g. 2026-10-04T14:22:31+02:00.
export function publishedDate(project) {
  const out = execFileSync("git", ["log", "--diff-filter=A", "--follow", "--format=%aI", "--", `public${project.video}`], {
    cwd: ROOT,
    encoding: "utf8"
  }).trim().split("\n").filter(Boolean);
  if (!out.length) throw new Error(`${project.video} is not committed yet`);
  return out[out.length - 1];
}

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const sentenceCase = (tag) => tag.charAt(0) + tag.slice(1).toLowerCase();
const frame = (aspect) => (Math.abs(aspect - 2) < 0.01 ? "2:1" : "16:9");

export function serviceFor(project) {
  const service = SERVICE_FOR_TAG[project.tag];
  if (!service) throw new Error(`No service mapped for tag "${project.tag}" (${project.slug})`);
  const cents = Math.min(...service.skus.map((sku) => STORE_CATALOG[sku].unitAmount));
  return { name: service.name, from: `€${cents / 100}` };
}

export function isHandWritten(slug) {
  const file = resolve(ROOT, "work", slug, "index.html");
  return existsSync(file) && !readFileSync(file, "utf8").includes(GENERATED_MARK);
}

export function renderCaseStudy(project, next) {
  const study = CASE_STUDIES[project.slug];
  if (!study?.onScreen) throw new Error(`No on-screen copy for ${project.slug} in src/work/caseStudies.js`);
  const url = `${SITE}/work/${project.slug}/`;
  const image = `${SITE}${project.poster}`;
  const webp = project.poster.replace(/\.jpg$/, ".webp");
  const service = serviceFor(project);
  const kind = sentenceCase(project.tag);
  const title = `${project.title} — ${kind}`;
  const metaDescription = `${project.title} ${kind.toLowerCase()} by SPNVISUALZ, the Oslo motion design studio. ${project.description}`;
  const story = (study.story || []).map((p) => `\n        <p>${esc(p)}</p>`).join("");
  const article = study.article
    ? `\n        <p>Read more in the Visual Lab: <a href="${study.article.href}">${esc(study.article.title)}</a>.</p>`
    : "";
  const jsonLd = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "CreativeWork",
        "@id": `${url}#project`,
        name: project.title,
        headline: title,
        description: project.description,
        url,
        image,
        video: {
          "@type": "VideoObject",
          name: `${project.title} — SPNVISUALZ`,
          description: study.onScreen,
          thumbnailUrl: image,
          contentUrl: `${SITE}${project.video}`,
          uploadDate: publishedDate(project)
        },
        creator: { "@id": `${SITE}/#organization` },
        genre: ["Motion design", kind],
        inLanguage: "en"
      },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "SPNVISUALZ", item: `${SITE}/` },
          { "@type": "ListItem", position: 2, name: "Selected Work", item: `${SITE}/work/` },
          { "@type": "ListItem", position: 3, name: project.title, item: url }
        ]
      }
    ]
  };

  return `<!doctype html>
${GENERATED_MARK}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
  <meta name="theme-color" content="#030207">
  <meta name="robots" content="index,follow,max-image-preview:large,max-snippet:-1,max-video-preview:-1">
  <meta name="description" content="${esc(metaDescription)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="SPNVISUALZ">
  <meta property="og:url" content="${url}">
  <meta property="og:title" content="${esc(title)} | SPNVISUALZ">
  <meta property="og:description" content="${esc(project.description)}">
  <meta property="og:image" content="${image}">
  <meta property="og:image:alt" content="${esc(project.title)} — still from the reel">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(title)} | SPNVISUALZ">
  <meta name="twitter:description" content="${esc(project.description)}">
  <meta name="twitter:image" content="${image}">
  <title>${esc(title)} | SPNVISUALZ</title>
  <link rel="icon" href="/favicon.ico" sizes="any">
  <link rel="icon" type="image/png" sizes="48x48" href="/assets/favicon-48.png">
  <link rel="apple-touch-icon" href="/assets/apple-touch-icon.png">
  <link rel="stylesheet" href="${PROJECT_CSS}">
  <script type="application/ld+json">
${JSON.stringify(jsonLd, null, 2).replace(/^/gm, "  ")}
  </script>
</head>
<body>
  <a class="work-skip" href="#project">Skip to project</a>
  <header class="work-nav">
    <div class="work-nav__inner">
      <a class="work-brand" href="/" aria-label="SPNVISUALZ home"><span>SPN</span>VISUALZ<small>VISUALS THAT CONNECT</small></a>
      <nav aria-label="Primary navigation"><a href="/work/">Work</a><a href="/#services">Services</a><a href="/websites/">Websites</a><a class="work-nav__cta" href="/#contact">Start a project ↗</a></nav>
    </div>
  </header>

  <main class="work-shell" id="project">
    <article class="project-hero">
      <div class="project-hero__head">
        <div><p class="work-kicker">Selected work / ${project.number} / ${esc(kind)}</p><h1>${esc(project.title)}</h1></div>
        <p class="project-lead">${esc(project.description)}</p>
      </div>
      <figure class="project-frame">
        <video style="aspect-ratio:${frame(project.aspect).replace(":", " / ")}" autoplay muted loop playsinline controls preload="metadata" poster="${webp}" aria-label="${esc(project.title)} — motion reel"><source src="${project.videoMobile}" type="video/mp4" media="(max-width: 640px)"><source src="${project.video}" type="video/mp4"></video>
      </figure>
    </article>

    <section class="project-details" aria-label="Project details">
      <dl class="project-facts">
        <div><dt>Discipline</dt><dd>${esc(kind)}</dd></div>
        <div><dt>Frame</dt><dd>${frame(project.aspect)} video loop</dd></div>
        <div><dt>Studio</dt><dd>SPNVISUALZ / Oslo</dd></div>
      </dl>
      <div class="project-copy">
        <h2>On screen</h2>
        <p>${esc(study.onScreen)}</p>${story}${article}
        <p>Want something in this direction? ${service.name} from ${service.from} — <a href="/#pricing">see pricing</a> or <a href="/#contact">start a project</a>.</p>
      </div>
    </section>

    <nav class="project-next" aria-label="Next project"><a href="/work/${next.slug}/"><span>Next project<strong>${esc(next.title)}</strong></span><i aria-hidden="true">↗</i></a></nav>
  </main>

  <footer class="work-shell work-footer"><span>© 2026 SPNVISUALZ / Oslo, Norway</span><nav aria-label="Footer navigation"><a href="/work/">All work</a><a href="/visual-lab/">Visual Lab</a><a href="/#contact">Contact</a></nav></footer>
  <script>if (matchMedia('(prefers-reduced-motion: reduce)').matches) document.querySelector('video')?.pause();</script>
</body>
</html>
`;
}

export function caseStudyPages() {
  return PROJECTS.map((project, i) => ({ project, next: PROJECTS[(i + 1) % PROJECTS.length] }))
    .filter(({ project }) => !isHandWritten(project.slug))
    .map(({ project, next }) => ({
      slug: project.slug,
      file: resolve(ROOT, "work", project.slug, "index.html"),
      html: renderCaseStudy(project, next)
    }));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const page of caseStudyPages()) {
    mkdirSync(dirname(page.file), { recursive: true });
    writeFileSync(page.file, page.html);
    console.log(`wrote work/${page.slug}/index.html`);
  }
}
